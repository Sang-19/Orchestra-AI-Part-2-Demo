import React, { useEffect, useState } from 'react';
import {
  AlertTriangle,
  Check,
  CheckCircle2,
  Copy,
  Download,
  ExternalLink,
  Printer,
  Send,
  Share2,
  X,
} from 'lucide-react';
import { apiClient } from '../services/apiClient';
import type {
  ResearchSession,
  SessionMessage,
  SourceRecord,
} from '../types/research';

interface ResearchReportViewProps {
  sessionId: string | null;
  sessions: ResearchSession[];
  onSelectSession: (id: string) => void;
}

function CitationText({
  text,
  sources,
  onSelectCitation,
}: {
  text: string;
  sources: SourceRecord[];
  onSelectCitation: (src: SourceRecord) => void;
}) {
  const parts = text.split(/(\[\d+\])/g);
  return (
    <>
      {parts.map((part, idx) => {
        const match = part.match(/^\[(\d+)\]$/);
        if (!match) return <React.Fragment key={idx}>{part}</React.Fragment>;
        const num = Number(match[1]);
        const src = sources.find((s) => s.citationNumber === num);
        return (
          <button
            key={idx}
            type="button"
            onClick={() => src && onSelectCitation(src)}
            className="inline-flex items-center px-1 mx-0.5 text-xs font-mono font-medium text-blue-700 bg-blue-50 hover:bg-blue-100 rounded transition-colors"
            title={src ? src.title : `Source ${num}`}
          >
            [{num}]
          </button>
        );
      })}
    </>
  );
}

export function ResearchReportView({
  sessionId,
  sessions,
  onSelectSession,
}: ResearchReportViewProps) {
  const [session, setSession] = useState<ResearchSession | null>(null);
  const [activeSource, setActiveSource] = useState<SourceRecord | null>(null);
  const [messages, setMessages] = useState<SessionMessage[]>([]);
  const [followUp, setFollowUp] = useState('');
  const [sendingFollowUp, setSendingFollowUp] = useState(false);
  const [followUpError, setFollowUpError] = useState<string | null>(null);
  const [copiedState, setCopiedState] = useState<'none' | 'markdown' | 'share'>('none');

  const completedSessions = sessions.filter(
    (s) => s.report && (s.status === 'completed' || s.status === 'completed_with_warnings')
  );
  const effectiveId = sessionId ?? completedSessions[0]?.id ?? null;

  useEffect(() => {
    if (!effectiveId) {
      setSession(null);
      return;
    }
    apiClient
      .getResearchSession(effectiveId)
      .then((res) => setSession(res.session))
      .catch(() => {});
    apiClient
      .getSessionMessages(effectiveId)
      .then((res) => setMessages(res.messages))
      .catch(() => {});
  }, [effectiveId]);

  const handleCopyMarkdown = async () => {
    if (!session?.report) return;
    await navigator.clipboard.writeText(session.report.markdownContent);
    setCopiedState('markdown');
    setTimeout(() => setCopiedState('none'), 2000);
  };

  const handleShareSummary = async () => {
    if (!session?.report) return;
    const summary = `${session.report.title}\n\n${session.report.executiveSummary}\n\nGenerated by Orchestra AI`;
    await navigator.clipboard.writeText(summary);
    setCopiedState('share');
    setTimeout(() => setCopiedState('none'), 2000);
  };

  const handleDownloadMarkdown = () => {
    if (!session?.report) return;
    const blob = new Blob([session.report.markdownContent], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${session.report.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').slice(0, 50)}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleSendFollowUp = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!session || !followUp.trim()) return;
    setSendingFollowUp(true);
    setFollowUpError(null);
    try {
      const res = await apiClient.postSessionMessage(session.id, followUp.trim());
      setMessages((prev) => [...prev, res.userMessage, res.assistantMessage]);
      setFollowUp('');
    } catch (err) {
      setFollowUpError(err instanceof Error ? err.message : 'Unable to send follow-up question.');
    } finally {
      setSendingFollowUp(false);
    }
  };

  if (!effectiveId || !session?.report) {
    return (
      <div className="bg-white border border-slate-200 rounded-xl p-10 text-center space-y-3">
        <h2 className="text-lg font-semibold text-slate-900">No Completed Research Report Selected</h2>
        <p className="text-sm text-slate-600 max-w-md mx-auto">
          Run a research workflow or select a completed session to inspect the verified report, inline citations, and contradictions.
        </p>
      </div>
    );
  }

  const report = session.report;
  const sources = session.checkpoint?.sources ?? [];
  const claims = session.checkpoint?.claims ?? [];
  const contradictions = session.checkpoint?.contradictions ?? [];
  const groundedness = session.groundedness;

  return (
    <div className="space-y-6">
      {/* Toolbar */}
      <div className="no-print bg-white border border-slate-200 rounded-xl p-4 flex flex-wrap items-center justify-between gap-3">
        <div className="flex items-center gap-3 min-w-0">
          {completedSessions.length > 0 && (
            <select
              aria-label="Select completed report"
              value={session.id}
              onChange={(e) => onSelectSession(e.target.value)}
              className="px-3 py-2 text-xs rounded-lg border border-slate-200 bg-white text-slate-700 max-w-xs"
            >
              {completedSessions.map((s) => (
                <option key={s.id} value={s.id}>
                  {s.report?.title || s.question}
                </option>
              ))}
            </select>
          )}
        </div>

        <div className="flex flex-wrap items-center gap-2">
          <button
            type="button"
            onClick={handleCopyMarkdown}
            className="inline-flex items-center gap-1.5 px-3 py-2 rounded-lg border border-slate-200 hover:bg-slate-50 text-xs font-medium text-slate-700 whitespace-nowrap"
          >
            {copiedState === 'markdown' ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5" />}
            <span>{copiedState === 'markdown' ? 'Copied Markdown' : 'Copy Report'}</span>
          </button>
          <button
            type="button"
            onClick={handleDownloadMarkdown}
            className="inline-flex items-center gap-1.5 px-3 py-2 rounded-lg border border-slate-200 hover:bg-slate-50 text-xs font-medium text-slate-700 whitespace-nowrap"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Download .md</span>
          </button>
          <button
            type="button"
            onClick={() => window.print()}
            className="inline-flex items-center gap-1.5 px-3 py-2 rounded-lg border border-slate-200 hover:bg-slate-50 text-xs font-medium text-slate-700 whitespace-nowrap"
          >
            <Printer className="w-3.5 h-3.5" />
            <span>Export PDF</span>
          </button>
          <button
            type="button"
            onClick={handleShareSummary}
            className="inline-flex items-center gap-1.5 px-3 py-2 rounded-lg bg-slate-900 hover:bg-slate-800 text-white text-xs font-medium whitespace-nowrap"
          >
            {copiedState === 'share' ? <Check className="w-3.5 h-3.5" /> : <Share2 className="w-3.5 h-3.5" />}
            <span>{copiedState === 'share' ? 'Summary Copied' : 'Share Summary'}</span>
          </button>
        </div>
      </div>

      {/* Groundedness Banner */}
      {groundedness && (
        <div
          className={`rounded-xl border p-4 flex flex-col sm:flex-row sm:items-center sm:justify-between gap-3 ${
            groundedness.passed
              ? 'bg-emerald-50 border-emerald-200 text-emerald-900'
              : 'bg-amber-50 border-amber-300 text-amber-950'
          }`}
        >
          <div className="flex items-start gap-2.5">
            {groundedness.passed ? (
              <CheckCircle2 className="w-5 h-5 text-emerald-700 shrink-0 mt-0.5" />
            ) : (
              <AlertTriangle className="w-5 h-5 text-amber-700 shrink-0 mt-0.5" />
            )}
            <div>
              <div className="text-sm font-semibold">
                {groundedness.passed
                  ? 'Groundedness Validation Passed'
                  : 'Groundedness Validation Warning — Review Flagged Claims'}
              </div>
              <div className="text-xs mt-0.5">{groundedness.summary}</div>
              {groundedness.unsupportedStatements.length > 0 && (
                <ul className="mt-2 list-disc list-inside text-xs space-y-0.5">
                  {groundedness.unsupportedStatements.map((u, idx) => (
                    <li key={idx}>{u}</li>
                  ))}
                </ul>
              )}
            </div>
          </div>
          <div className="text-xs font-mono font-semibold tabular-nums shrink-0">
            Score: {Math.round(groundedness.score * 100)}%
          </div>
        </div>
      )}

      {/* Main Report + Evidence Drawer Split */}
      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6 items-start">
        <article className="lg:col-span-2 bg-white border border-slate-200 rounded-xl p-6 sm:p-10 space-y-8">
          <header className="pb-6 border-b border-slate-200">
            <div className="text-xs text-slate-500 font-mono tabular-nums">
              Generated {new Date(report.generatedAt).toLocaleString()} · {sources.length} Sources ·{' '}
              {claims.length} Claims Audited
            </div>
            <h1 className="mt-2 text-2xl sm:text-3xl font-semibold tracking-tight text-slate-900">
              {report.title}
            </h1>
          </header>

          <section className="space-y-2">
            <h2 className="text-lg font-semibold text-slate-900">Executive Summary</h2>
            <p className="text-sm text-slate-700 leading-relaxed">
              <CitationText
                text={report.executiveSummary}
                sources={sources}
                onSelectCitation={setActiveSource}
              />
            </p>
          </section>

          <section className="space-y-2">
            <h2 className="text-lg font-semibold text-slate-900">Introduction</h2>
            <p className="text-sm text-slate-700 leading-relaxed">
              <CitationText
                text={report.introduction}
                sources={sources}
                onSelectCitation={setActiveSource}
              />
            </p>
          </section>

          <section className="space-y-2">
            <h2 className="text-lg font-semibold text-slate-900">Research Objectives</h2>
            <ul className="list-disc list-inside space-y-1.5 text-sm text-slate-700">
              {report.researchObjectives.map((obj, idx) => (
                <li key={idx}>{obj}</li>
              ))}
            </ul>
          </section>

          <section className="space-y-2">
            <h2 className="text-lg font-semibold text-slate-900">Methodology</h2>
            <p className="text-sm text-slate-700 leading-relaxed">
              <CitationText
                text={report.methodology}
                sources={sources}
                onSelectCitation={setActiveSource}
              />
            </p>
          </section>

          <section className="space-y-2">
            <h2 className="text-lg font-semibold text-slate-900">Detailed Findings</h2>
            <p className="text-sm text-slate-700 leading-relaxed whitespace-pre-line">
              <CitationText
                text={report.detailedFindings}
                sources={sources}
                onSelectCitation={setActiveSource}
              />
            </p>
          </section>

          {report.topicAnalysis.length > 0 && (
            <section className="space-y-4">
              <h2 className="text-lg font-semibold text-slate-900">Topic-Wise Analysis</h2>
              <div className="space-y-4">
                {report.topicAnalysis.map((topic) => (
                  <div key={topic.subtopicId} className="p-5 rounded-lg border border-slate-200 space-y-2.5">
                    <h3 className="text-base font-semibold text-slate-900">{topic.title}</h3>
                    <p className="text-sm text-slate-700 leading-relaxed">
                      <CitationText
                        text={topic.summary}
                        sources={sources}
                        onSelectCitation={setActiveSource}
                      />
                    </p>
                    {topic.keyDiscoveries.length > 0 && (
                      <div>
                        <div className="text-xs font-semibold text-slate-700">Key Discoveries</div>
                        <ul className="mt-1 list-disc list-inside text-xs text-slate-600 space-y-1">
                          {topic.keyDiscoveries.map((d, i) => (
                            <li key={i}>
                              <CitationText
                                text={d}
                                sources={sources}
                                onSelectCitation={setActiveSource}
                              />
                            </li>
                          ))}
                        </ul>
                      </div>
                    )}
                    {topic.knowledgeGaps.length > 0 && (
                      <div>
                        <div className="text-xs font-semibold text-amber-800">Knowledge Gaps</div>
                        <ul className="mt-1 list-disc list-inside text-xs text-slate-600 space-y-1">
                          {topic.knowledgeGaps.map((g, i) => (
                            <li key={i}>{g}</li>
                          ))}
                        </ul>
                      </div>
                    )}
                  </div>
                ))}
              </div>
            </section>
          )}

          {/* Preserved Contradictions */}
          <section className="space-y-3">
            <h2 className="text-lg font-semibold text-slate-900">Contradictory Findings</h2>
            <p className="text-sm text-slate-700 leading-relaxed">
              {report.contradictoryFindingsSummary}
            </p>
            {contradictions.length > 0 && (
              <div className="space-y-3">
                {contradictions.map((c) => (
                  <div key={c.id} className="p-4 rounded-lg border border-amber-200 bg-amber-50/40 space-y-2">
                    <div className="flex items-center justify-between gap-2 text-xs">
                      <span className="font-semibold text-slate-900">{c.topic}</span>
                      <span className="font-mono text-amber-800 capitalize">
                        {c.resolutionStatus.replace('_', ' ')}
                      </span>
                    </div>
                    <p className="text-xs text-slate-700">{c.summary}</p>
                    <div className="grid grid-cols-1 sm:grid-cols-2 gap-2 text-xs text-slate-600 pt-1">
                      <div className="p-2.5 rounded bg-white border border-slate-200">
                        <span className="font-semibold text-slate-800">Position A: </span>
                        {c.claimAStatement}
                      </div>
                      <div className="p-2.5 rounded bg-white border border-slate-200">
                        <span className="font-semibold text-slate-800">Position B: </span>
                        {c.claimBStatement}
                      </div>
                    </div>
                  </div>
                ))}
              </div>
            )}
          </section>

          <section className="space-y-2">
            <h2 className="text-lg font-semibold text-slate-900">Limitations</h2>
            <ul className="list-disc list-inside space-y-1 text-sm text-slate-700">
              {report.limitations.map((lim, idx) => (
                <li key={idx}>{lim}</li>
              ))}
            </ul>
          </section>

          <section className="space-y-2">
            <h2 className="text-lg font-semibold text-slate-900">Conclusion</h2>
            <p className="text-sm text-slate-700 leading-relaxed">
              <CitationText
                text={report.conclusion}
                sources={sources}
                onSelectCitation={setActiveSource}
              />
            </p>
          </section>

          <section className="pt-6 border-t border-slate-200 space-y-3">
            <h2 className="text-lg font-semibold text-slate-900">References</h2>
            <div className="space-y-2">
              {sources.map((src) => (
                <button
                  key={src.id}
                  type="button"
                  onClick={() => setActiveSource(src)}
                  className="w-full text-left p-3 rounded-lg border border-slate-200 hover:bg-slate-50 flex items-start justify-between gap-3 transition-colors"
                >
                  <div className="min-w-0">
                    <div className="text-sm font-medium text-slate-900">
                      [{src.citationNumber}] {src.title}
                    </div>
                    <div className="text-xs text-slate-500 mt-0.5">
                      {src.domain} · {src.credibilityTier} · Credibility{' '}
                      {Math.round(src.credibilityScore * 100)}%
                      {src.publishedAt ? ` · ${src.publishedAt}` : ''}
                    </div>
                  </div>
                  <span className="text-xs text-blue-700 font-medium shrink-0">Inspect</span>
                </button>
              ))}
            </div>
          </section>
        </article>

        {/* Right Column: Citation Inspector + Follow-up Q&A */}
        <div className="no-print space-y-6">
          {/* Source Inspector */}
          <div className="bg-white border border-slate-200 rounded-xl p-5 space-y-3">
            <div className="flex items-center justify-between">
              <h3 className="text-sm font-semibold text-slate-900">Evidence Inspector</h3>
              {activeSource && (
                <button
                  type="button"
                  onClick={() => setActiveSource(null)}
                  aria-label="Close source inspector"
                  className="text-slate-400 hover:text-slate-700"
                >
                  <X className="w-4 h-4" />
                </button>
              )}
            </div>

            {activeSource ? (
              <div className="space-y-3">
                <div className="text-sm font-medium text-slate-900">
                  [{activeSource.citationNumber}] {activeSource.title}
                </div>
                <div className="text-xs text-slate-500">
                  {activeSource.domain} · {activeSource.credibilityTier} · Score{' '}
                  {Math.round(activeSource.credibilityScore * 100)}%
                </div>
                <p className="text-xs text-slate-700 leading-relaxed p-3 bg-slate-50 rounded-lg border border-slate-200">
                  {activeSource.snippet}
                </p>
                <div className="text-xs text-slate-600">
                  <span className="font-medium text-slate-800">Credibility Reasoning: </span>
                  {activeSource.credibilityReasoning}
                </div>
                {activeSource.url.startsWith('http') && (
                  <a
                    href={activeSource.url}
                    target="_blank"
                    rel="noreferrer"
                    className="inline-flex items-center gap-1.5 text-xs font-medium text-blue-700 hover:underline"
                  >
                    <span>Open Original Source</span>
                    <ExternalLink className="w-3.5 h-3.5" />
                  </a>
                )}
              </div>
            ) : (
              <p className="text-xs text-slate-500">
                Click any inline citation marker like <span className="font-mono text-blue-700">[1]</span> or reference row to inspect the original excerpt and credibility reasoning.
              </p>
            )}
          </div>

          {/* Persistent Follow-Up Q&A Memory */}
          <div className="bg-white border border-slate-200 rounded-xl p-5 space-y-4">
            <div>
              <h3 className="text-sm font-semibold text-slate-900">Evidence-Grounded Follow-Up</h3>
              <p className="text-xs text-slate-500 mt-0.5">
                Ask clarifying questions answered strictly from this session’s verified sources.
              </p>
            </div>

            <div className="space-y-2.5 max-h-64 overflow-y-auto">
              {messages.length === 0 ? (
                <div className="text-xs text-slate-400">No follow-up queries asked yet.</div>
              ) : (
                messages.map((m) => (
                  <div
                    key={m.id}
                    className={`p-3 rounded-lg text-xs leading-relaxed ${
                      m.role === 'user'
                        ? 'bg-slate-900 text-slate-100 ml-4'
                        : 'bg-slate-50 border border-slate-200 text-slate-800 mr-4'
                    }`}
                  >
                    <div>{m.content}</div>
                  </div>
                ))
              )}
            </div>

            {followUpError && (
              <div className="text-xs text-red-700 bg-red-50 border border-red-200 p-2 rounded">
                {followUpError}
              </div>
            )}

            <form onSubmit={handleSendFollowUp} className="flex items-center gap-2">
              <input
                type="text"
                aria-label="Follow-up question"
                value={followUp}
                onChange={(e) => setFollowUp(e.target.value)}
                placeholder="Ask about a claim or source..."
                className="flex-1 px-3 py-2 text-xs rounded-lg border border-slate-300 focus:outline-none focus:ring-2 focus:ring-blue-600"
              />
              <button
                type="submit"
                disabled={sendingFollowUp || !followUp.trim()}
                aria-label="Send follow-up question"
                className="p-2 rounded-lg bg-blue-700 hover:bg-blue-800 disabled:opacity-50 text-white"
              >
                <Send className="w-3.5 h-3.5" />
              </button>
            </form>
          </div>
        </div>
      </div>
    </div>
  );
}
